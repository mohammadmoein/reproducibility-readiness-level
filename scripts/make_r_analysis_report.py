"""Generate `artifacts/analysis/r-analysis-results.md` from `artifacts/analysis/r-analysis.json`.

    uv run lakdb rstats run
    uv run python scripts/make_r_analysis_report.py

Same convention as `scripts/make_stage2_report.py`: every table is derived from the saved
analysis JSON, nothing is transcribed by hand, and the file can be regenerated at any time.
No threshold on R is selected and no gate is decided here.
"""

from __future__ import annotations

import argparse
import json
import pathlib
from typing import Any

SPEC = "docs/stage2-ara.md"


def fmt(value: Any, places: int = 4, percent: bool = False) -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, int):
        return str(value)
    if percent:
        return f"{value:.1%}"
    return f"{value:.{places}f}"


def signed(value: Any, places: int = 4) -> str:
    return "—" if value is None else f"{value:+.{places}f}"


def ci(block: dict[str, Any] | None, places: int = 4, key: str = "") -> str:
    if not block or block.get("ci_low") is None:
        return "—"
    return f"[{block['ci_low']:+.{places}f}, {block['ci_high']:+.{places}f}]" if key == "signed" else (
        f"[{block['ci_low']:.{places}f}, {block['ci_high']:.{places}f}]"
    )


def p(value: Any) -> str:
    if value is None:
        return "p —"
    return "p<0.001" if value < 0.001 else f"p={value:.3f}"


def sentence(text: str) -> str:
    """Analysis notes are phrased as fragments in the JSON; start them as sentences."""
    return text[:1].upper() + text[1:] if text else text


def rho_cell(block: dict[str, Any]) -> str:
    if block.get("rho") is None:
        return f"— (n={block.get('n')})"
    cell = f"{block['rho']:+.3f} {ci(block, 3, 'signed')}, {p(block.get('p_value'))}, n={block['n']}"
    return cell + (" **small n**" if block.get("small_n_warning") else "")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", default="artifacts/analysis/r-analysis.json")
    parser.add_argument("--output", default="artifacts/analysis/r-analysis-results.md")
    parser.add_argument("--figures", default="artifacts/analysis/figures")
    args = parser.parse_args()

    payload = json.loads(pathlib.Path(args.input).read_text(encoding="utf-8"))
    prov = payload["provenance"]
    a = payload["analyses"]
    out: list[str] = []
    w = out.append

    w("# R analysis results — Stage 2 analytics over LAK 2021–2026\n")
    w(f"Generated by `scripts/make_r_analysis_report.py` from `{args.input}` on")
    w(f"{prov['generated_on']}. Every table is derived from that file, which is itself")
    w(f"produced by `lakdb rstats run` directly from `{prov['database']}` and the stored ARA")
    w(f"artifacts; nothing is transcribed by hand. Implements `{SPEC}`.\n")
    w("**No threshold on R is selected and no gate is decided in this document.** The one")
    w("confirmatory test is A2.1; every other analysis is exploratory and labelled as such")
    w("in the JSON. No family-wise correction is applied across the exploratory tests, so")
    w("none of their p-values should be read as confirmation.\n")

    w("## 1. Provenance\n")
    w("| experiment | model | reps | effort | papers | upstream commit |")
    w("|---|---|---|---|---|---|")
    for experiment in prov["experiments"]:
        w(
            f"| `{experiment['name']}` | {experiment['model']} | {experiment['repetitions']} "
            f"| {experiment['reasoning_effort']} | {experiment['papers_complete']} "
            f"| `{experiment['upstream_commit'][:12]}` |"
        )
    w(
        f"\n{prov['papers']} papers, {prov['assessments']} assessments, "
        f"{len(prov['analyses_run'])} analyses. Bootstrap: "
        f"{prov['bootstrap_resamples']} resamples at seed {prov['bootstrap_seed']}. "
        f"{sentence(prov['read_only'])}.\n"
    )
    w("Self-checks:\n")
    w("| check | result | detail |")
    w("|---|---|---|")
    for key, check in payload["self_checks"].items():
        if not isinstance(check, dict) or "ok" not in check:
            continue
        detail = ", ".join(
            f"{k}={v}"
            for k, v in check.items()
            if k not in ("ok", "note", "expected", "observed") and not isinstance(v, (dict, list))
        )
        w(f"| `{key}` | {'pass' if check['ok'] else '**FAIL**'} | {detail} |")
    w("")

    w("## 2. What R looks like (A1.1, A1.2, A1.3)\n")
    pooled = a["A1.1"]["pooled"]
    w("| statistic | value |")
    w("|---|---|")
    for label, key in (
        ("papers", "n"), ("mean", "mean"), ("SD", "sd"), ("min", "min"),
        ("Q1", "q1"), ("median", "median"), ("Q3", "q3"), ("max", "max"), ("skew", "skew"),
    ):
        w(f"| {label} | {fmt(pooled[key])} |")
    w(f"\nMean R with a 95% bootstrap CI: {fmt(a['A1.1']['pooled_mean_ci']['estimate'])} "
      f"{ci(a['A1.1']['pooled_mean_ci'])}.\n")
    w("| year | papers | mean R | 95% CI | median | SD |")
    w("|---|---|---|---|---|---|")
    for year, block in a["A1.1"]["by_year"].items():
        w(
            f"| {year} | {block['n']} | {fmt(block['mean'])} | {ci(block['mean_ci'])} "
            f"| {fmt(block['median'])} | {fmt(block['sd'])} |"
        )

    claim = a["A1.2"]
    w("\n### R by claim type (A1.2, exploratory)\n")
    w("| claim type | papers | median R | 95% CI |")
    w("|---|---|---|---|")
    for tier in claim.get("order_by_median", []):
        block = claim["per_group"][tier]
        w(
            f"| {tier} | {block['n']} | {fmt(block['median'])} "
            f"| [{fmt(block['median_ci_low'])}, {fmt(block['median_ci_high'])}] |"
        )
    w(
        f"\nKruskal–Wallis H={fmt(claim.get('h_statistic'), 3)} on "
        f"{claim.get('degrees_of_freedom')} df, {p(claim.get('p_value'))}, "
        f"eta-squared {fmt(claim.get('eta_squared'), 4)}. Eta-squared is the share of the "
        "rank variance the grouping accounts for, so a value near zero means the claim "
        "types barely separate R however small the p-value is.\n"
    )

    kind = a["A1.3"]
    w("### R by paper kind (A1.3, exploratory)\n")
    w(
        f"Long papers (n={kind['n_a']}, median {fmt(kind['median_a'])}) against short "
        f"(n={kind['n_b']}, median {fmt(kind['median_b'])}): Mann–Whitney "
        f"U={fmt(kind.get('u_statistic'), 1)}, {p(kind.get('p_value'))}, rank-biserial "
        f"r={signed(kind.get('rank_biserial_r'), 3)} {ci(kind, 3, 'signed')}.\n"
    )

    w("## 3. R_c, R_s and the stage scores (A1.4, A1.5)\n")
    components = a["A1.4"]
    ceiling = components["structural_ceiling"]
    variance = components["variance_explained"]
    w("| quantity | mean | median | SD |")
    w("|---|---|---|---|")
    for label, key in (("content R_c", "content_score"), ("structural R_s", "structural_score")):
        block = components[key]
        w(f"| {label} | {fmt(block['mean'])} | {fmt(block['median'])} | {fmt(block['sd'])} |")
    w(
        f"\nR_s sits at exactly 1.000 for {ceiling['at_1_000']}/{ceiling['of']} papers "
        f"({fmt(ceiling['fraction'], percent=True)}); R_c never saturates. "
        f"R_c alone explains {fmt(variance['content_only_r_squared'], percent=True)} of the "
        f"between-paper variance in R, against "
        f"{fmt(variance['structural_only_r_squared'], percent=True)} for R_s and "
        f"{fmt(variance['both_r_squared'], percent=True)} for both together.\n"
    )
    w("| correlation | Spearman rho, 95% CI, p, n |")
    w("|---|---|")
    for label, key in (
        ("R against R_c", "r_vs_content"),
        ("R against R_s", "r_vs_structural"),
        ("R_c against R_s", "content_vs_structural"),
    ):
        w(f"| {label} | {rho_cell(components[key])} |")
    w(f"\n{sentence(components['interpretation'])}. This is why `R_s` is not reported as a separate")
    w("finding anywhere in the paper.\n")

    stages = a["A1.5"]
    w("### Which stage score carries the variance (A1.5, exploratory)\n")
    w("| stage score | papers | missing | mean | variance | Spearman with R | standardised beta |")
    w("|---|---|---|---|---|---|---|")
    for score, block in stages["per_score"].items():
        beta = stages["standardised_regression"]["terms"].get(score, {})
        w(
            f"| `{score}` | {block['n']} | {block['missing']} | {fmt(block['mean'])} "
            f"| {fmt(block['variance'])} | {rho_cell(block['spearman_with_r'])} "
            f"| {signed(beta.get('coefficient'), 3)} "
            f"[{signed(beta.get('ci_low'), 3)}, {signed(beta.get('ci_high'), 3)}] |"
        )
    w(
        f"\nThe joint regression uses {stages['complete_cases']} complete cases; "
        f"{stages['dropped_incomplete']} papers are dropped because at least one stage score "
        f"is missing. {sentence(stages['missingness_note'])}. On rank correlation the variance carrier "
        f"is `{stages['variance_carrier']}`.\n"
    )

    w("## 4. The trend — PRIMARY (A2.1)\n")
    primary = a["A2.1"]
    contrast = primary["contrast"]
    w(f"**Hypothesis.** {primary['hypothesis']}.\n")
    w("| quantity | slope per year | 95% CI |")
    w("|---|---|---|")
    w(
        f"| R, raw | {signed(primary['r_slope_sd_per_year']['raw_slope_per_year'])} "
        f"| {ci(primary['r_regression_on_year']['terms']['year'], 4, 'signed')} |"
    )
    w(
        f"| R, standardised (SD/year) | {signed(primary['r_slope_sd_per_year']['estimate'])} "
        f"| {ci(primary['r_slope_sd_per_year'], 4, 'signed')} |"
    )
    w(
        "| verified data sharing, raw (proportion/year) | "
        f"{signed(primary['sharing_slope_proportion_per_year']['estimate'])} "
        f"| {ci(primary['sharing_slope_proportion_per_year'], 4, 'signed')} |"
    )
    w(
        "| verified data sharing, standardised (SD/year) | "
        f"{signed(primary['sharing_slope_sd_per_year']['estimate'])} "
        f"| {ci(primary['sharing_slope_sd_per_year'], 4, 'signed')} |"
    )
    w(
        f"| gap (sharing − R), SD/year | {signed(contrast['gap_sd_per_year'])} "
        f"| {ci(contrast, 4, 'signed')} |"
    )
    w(f"\n{sentence(contrast['units'])}.\n")
    w(
        f"- R slope CI excludes the sharing slope: **{fmt(contrast['r_ci_excludes_sharing_slope'])}**.\n"
        f"- Gap CI excludes zero: **{fmt(contrast['gap_ci_excludes_zero'])}**.\n"
        f"- Between-paper SD of R: {fmt(primary['r_between_paper_sd'])}."
    )
    w(f"\n{sentence(contrast['framing'])}.\n")
    w("| year | papers | mean R | corpus papers | verified data | proportion |")
    w("|---|---|---|---|---|---|")
    for year, block in primary["sharing_by_year"].items():
        w(
            f"| {year} | {block['analysis_set_papers']} "
            f"| {fmt(primary['mean_r_by_year'][year])} | {block['papers']} | {block['data']} "
            f"| {fmt(block['proportion'], percent=True)} |"
        )
    trend = primary["cochran_armitage_sharing_corpus"]
    kw = primary["kruskal_across_years"]
    w(
        f"\nCochran–Armitage trend on the corpus-wide sharing proportion: "
        f"z={fmt(trend.get('z'), 3)}, {p(trend.get('p_value'))}, n={trend.get('n')}. "
        f"Kruskal–Wallis on R across the six years: H={fmt(kw.get('h_statistic'), 3)}, "
        f"{p(kw.get('p_value'))}, eta-squared {fmt(kw.get('eta_squared'))}.\n"
    )
    w("| correlation | Spearman rho, 95% CI, p, n |")
    w("|---|---|")
    w(f"| year against paper-level R | {rho_cell(primary['spearman_year_vs_paper_r'])} |")
    w(f"| year against yearly mean R | {rho_cell(primary['spearman_year_vs_yearly_mean_r'])} |")
    w(f"\n{sentence(primary['denominators'])}.\n")

    w("### Confound controls (A2.2, exploratory)\n")
    controls = a["A2.2"]
    year_coefficient = controls["year_coefficient"]
    w("| term | coefficient | 95% CI | significance |")
    w("|---|---|---|---|")
    for name, term in controls["controlled"]["terms"].items():
        if name == "intercept":
            continue
        w(
            f"| `{name}` | {signed(term['coefficient'], 5)} "
            f"| {ci(term, 5, 'signed')} | {p(term['p_value'])} |"
        )
    w(
        f"\nThe year coefficient is {signed(year_coefficient['before']['coefficient'], 5)} "
        f"uncontrolled and {signed(year_coefficient['after']['coefficient'], 5)} once paper "
        f"length, kind, claim-type mix and node count enter: an attenuation of "
        f"{fmt(year_coefficient['attenuation'], percent=True)}, sign flipped: "
        f"{fmt(year_coefficient['sign_flipped'])}. Model R-squared rises from "
        f"{fmt(controls['uncontrolled']['r_squared'], 3)} to "
        f"{fmt(controls['controlled']['r_squared'], 3)}. Length alone against R: "
        f"{rho_cell(controls['length_vs_r'])}.\n"
    )
    w(f"{sentence(controls['interpretation_rule'])}.\n")
    w(f"Reference claim tier for the dummies: {controls['reference_claim_tier']}.\n")

    w("### Is sharing the same virtue as describing? (A2.3, exploratory)\n")
    sharing = a["A2.3"]
    w("| Stage 1 signal | n with | n without | median R with | median R without | rank-biserial r, 95% CI | significance |")
    w("|---|---|---|---|---|---|---|")
    for name, test in sharing["tests"].items():
        w(
            f"| `{name}` | {test['n_a']} | {test['n_b']} | {fmt(test['median_a'])} "
            f"| {fmt(test['median_b'])} | {signed(test.get('rank_biserial_r'), 3)} "
            f"{ci(test, 3, 'signed')} | {p(test.get('p_value'))} |"
        )
    environment = sharing["environment"]
    partial = sharing["partial_correlation"]
    w(
        f"\nEnvironment score E is scored for {environment['papers_with_e']} papers and takes "
        f"{environment['distinct_e_values']} distinct values "
        f"(mean {fmt(environment['e_score'].get('mean'))}, max "
        f"{fmt(environment['e_score'].get('max'))}). {sentence(environment['d1_prediction'])}. "
        f"R against E: {rho_cell(environment['spearman_r_vs_e'])}.\n"
    )
    w(
        f"Partial correlation of R with verified retrievable data, controlling for year and "
        f"paper length: {signed(partial.get('partial_rho'), 3)} {ci(partial, 3, 'signed')} "
        f"on n={partial['n']}. Largest single effect: `{sharing['largest_effect']}`.\n"
    )
    w(f"{sentence(sharing['interpretation_rule'])}.\n")

    w("## 5. Instrument behaviour (A3)\n")
    stability = a["A3.1"]
    pooled_stability = stability["pooled"]
    w("| statistic | pooled |")
    w("|---|---|")
    for label, key, percent in (
        ("papers", "n", False), ("mean within-paper SD", "sd_mean", False),
        ("median SD", "sd_median", False), ("max SD", "sd_max", False),
        ("between-paper SD of mean R", "r_between", False),
        ("within/between ratio", "ratio", False),
    ):
        w(f"| {label} | {fmt(pooled_stability[key])} |")
    w(
        f"| SD at or below 0.09 | {pooled_stability['le09']}/{pooled_stability['n']} |\n"
        f"| SD below 0.02 | {pooled_stability['lt02']}/{pooled_stability['n']} |"
    )
    w(
        f"\nMean within-paper SD with a bootstrap CI: "
        f"{fmt(stability['pooled_sd_mean_ci']['estimate'])} {ci(stability['pooled_sd_mean_ci'])}, "
        f"against ARA's reported band of {stability['ara_reference_band']}. "
        f"{sentence(stability['note'])}.\n"
    )
    w("| year | papers | mean SD | max SD | within/between ratio |")
    w("|---|---|---|---|---|")
    for year, block in stability["by_year"].items():
        w(
            f"| {year} | {block['n']} | {fmt(block['sd_mean'])} | {fmt(block['sd_max'])} "
            f"| {fmt(block['ratio'], 3)} |"
        )

    w("\n### Does stability depend on anything? (A3.2, A3.3, A3.4)\n")
    w("| relation | statistic |")
    w("|---|---|")
    w(f"| SD against R | {rho_cell(a['A3.2']['spearman_sd_vs_r'])} |")
    w(f"| SD against log paper length | {rho_cell(a['A3.3']['spearman_sd_vs_length'])} |")
    w(f"| SD against node count | {rho_cell(a['A3.3']['spearman_sd_vs_node_count'])} |")
    quadratic = a["A3.2"]["quadratic_regression"]["terms"]["r_centred_squared"]
    w(
        f"\nRegressing SD on R and R-squared gives a quadratic term of "
        f"{signed(quadratic['coefficient'], 4)} {ci(quadratic, 4, 'signed')} "
        f"({p(quadratic['p_value'])}); mid-range papers least stable: "
        f"{fmt(a['A3.2']['mid_range_least_stable'])}.\n"
    )
    w("| SD by quintile of R | R range | papers | mean SD |")
    w("|---|---|---|---|")
    for name, block in a["A3.2"]["sd_by_r_quintile"].items():
        low, high = block["r_range"]
        w(f"| {name} | {fmt(low, 3)}–{fmt(high, 3)} | {block['n']} | {fmt(block['mean_sd'])} |")
    jaccard = a["A3.4"]
    w("\n| node class | mean pairwise Jaccard | 95% CI | identical across all three runs |")
    w("|---|---|---|---|")
    for cls, block in jaccard["mean_pairwise_jaccard"].items():
        w(
            f"| {cls} | {fmt(block['mean_ci']['estimate'], 3)} | {ci(block['mean_ci'], 3)} "
            f"| {jaccard['identical_node_sets'][cls]} |"
        )
    w(f"\n{sentence(jaccard['method'])}.\n")

    w("### Cross-time replication of a hosted model (A3.5, exploratory)\n")
    drift = a["A3.5"]
    if drift.get("status"):
        w(f"{drift['status']} (n={drift['n']}).\n")
    else:
        altman = drift["bland_altman"]
        w(
            f"`{drift['experiments'][0]}` and `{drift['experiments'][1]}` share "
            f"**{drift['n']} papers** with byte-identical PDFs, the same model, effort and "
            f"upstream commit, {drift['days_apart']} days apart.\n"
        )
        w("| quantity | value |")
        w("|---|---|")
        w(f"| paired papers | {drift['n']} |")
        w(f"| mean difference (new − old) | {signed(drift['mean_difference'])} |")
        w(f"| 95% CI on the mean difference | {ci(drift['mean_difference_ci'], 4, 'signed')} |")
        w(f"| Wilcoxon signed-rank | {p(drift['wilcoxon']['p_value'])} |")
        w(f"| Bland–Altman bias | {signed(altman['bias'])} |")
        w(f"| SD of differences | {fmt(altman['sd_of_differences'])} |")
        w(
            f"| 95% limits of agreement | [{signed(altman['limits_of_agreement'][0])}, "
            f"{signed(altman['limits_of_agreement'][1])}] |"
        )
        w(f"| papers outside the limits | {altman['outside_limits']} |")
        w(f"| Spearman on the ranking | {rho_cell(drift['spearman_ranking'])} |")
        w(
            f"| median within-paper SD, new runs | {fmt(drift['median_within_paper_sd_new'])} |"
        )
        w(f"\n{sentence(drift['caveat'])}.\n")

    w("## 6. Threshold sensitivity, without picking a threshold (A4)\n")
    tau = a["A4.1"]
    noise = a["A4.2"]
    w(f"{sentence(tau['note'])}.\n")
    w(
        f"Over tau_R in {tau['tau_range']} at step {tau['step']}, the count of papers at L2 "
        f"falls from {tau['span']['l2_at_0_30']} to {tau['span']['l2_at_0_70']}: "
        f"{tau['span']['papers_moved']} papers change rung on the choice of threshold alone. "
        f"The curve is steepest at tau_R={tau['steepest_point']['tau']}, where a 0.01 step "
        f"moves {fmt(tau['steepest_point']['papers_per_0_01_tau'], 1)} papers.\n"
    )
    w("| tau_R | L2 under mean R | under the lowest repetition | under the highest | noise width |")
    w("|---|---|---|---|---|")
    for point in noise["noise_band"]:
        if round(point["tau"] * 100) % 5:
            continue
        w(
            f"| {point['tau']:.2f} | {point['l2_mean']} | {point['l2_min_draw']} "
            f"| {point['l2_max_draw']} | {point['noise_width']} |"
        )
    widest = noise["widest_noise_band"]
    w(
        f"\nThe mean noise width is {fmt(noise['mean_noise_width'], 1)} papers and the widest "
        f"is {widest['noise_width']} at tau_R={widest['tau']:.2f}. {sentence(noise['interpretation'])}.\n"
    )

    w("## 7. Node-level deficit report (A5)\n")
    deficit = a["A5.1"]
    w(f"Scale: {deficit['scale']}. Pooling: {deficit['pooling']}.\n")
    w("| node class | papers | mean score | 95% CI | median |")
    w("|---|---|---|---|---|")
    for cls, block in deficit["by_node_class"].items():
        w(
            f"| {cls} | {block['n']} | {fmt(block['mean_ci']['estimate'], 2)} "
            f"| {ci(block['mean_ci'], 2)} | {fmt(block['median'], 2)} |"
        )
    w(
        f"\nThe bottleneck is **{deficit['bottleneck']}** nodes; worst first, the ordering is "
        f"{', '.join(deficit['ranking_worst_first'])}.\n"
    )

    gap = a["A5.2"]
    w("### The parameter gap (A5.2)\n")
    w(f"**{gap['headline']}.**\n")
    w(f"{sentence(gap['definition'])}.\n")
    w("| resource | required | named | completion | per-paper mean | 95% CI |")
    w("|---|---|---|---|---|---|")
    for label, key in (("parameters", "parameters"), ("tools", "tools")):
        block = gap[key]
        w(
            f"| {label} | {fmt(block['required'], 1)} "
            f"| {fmt(block['counted_towards_completion'], 1)} "
            f"| {fmt(block['completion'], percent=True)} "
            f"| {fmt(block['per_paper_mean_ci']['estimate'], 3)} "
            f"| {ci(block['per_paper_mean_ci'], 3)} |"
        )
    w(
        f"\nExcluded from the denominator: "
        f"{gap['excluded']['process_nodes_without_required_parameters']} process nodes list no "
        f"required parameters; {gap['excluded']['process_nodes_naming_more_than_required']} name "
        f"more than they require and are capped.\n"
    )
    w("| year | parameter completion | tool completion |")
    w("|---|---|---|")
    for year, block in gap["by_year"].items():
        w(
            f"| {year} | {fmt(block['parameters']['completion'], percent=True)} "
            f"| {fmt(block['tools']['completion'], percent=True)} |"
        )
    w("\n| claim type | parameter completion | tool completion |")
    w("|---|---|---|")
    for tier, block in gap["by_claim_tier"].items():
        w(
            f"| {tier} | {fmt(block['parameters']['completion'], percent=True)} "
            f"| {fmt(block['tools']['completion'], percent=True)} |"
        )

    clarity = a["A5.3"]
    w(f"\n### Algorithm clarity (A5.3)\n")
    w(f"Scale: {clarity['scale']}.\n")
    w("| level | nodes | fraction |")
    w("|---|---|---|")
    for level, count in clarity["node_level_counts"].items():
        w(f"| {level} | {count} | {fmt(clarity['node_level_fractions'][level], percent=True)} |")
    w(
        f"\n{clarity['nodes_counted']} process nodes across all repetitions. Paper-level mean "
        f"clarity {fmt(clarity['paper_level_mean']['mean'], 3)} "
        f"(SD {fmt(clarity['paper_level_mean']['sd'], 3)}). Against R_c: "
        f"{rho_cell(clarity['spearman_with_content_score'])}.\n"
    )

    chain = a["A5.4"]
    broken = chain["broken_evidence_chain"]
    w("### Evidence-chain integrity (A5.4)\n")
    w("| wiring metric | mean | 95% CI | at 1.000 | below 1.000 |")
    w("|---|---|---|---|---|")
    for metric, block in chain["metrics"].items():
        w(
            f"| `{metric}` | {fmt(block['mean_ci']['estimate'], 3)} | {ci(block['mean_ci'], 3)} "
            f"| {block['at_1_000']} | {block['below_1_000']} |"
        )
    w(
        f"\n**{broken['papers']} of {broken['of']} papers "
        f"({fmt(broken['fraction'], percent=True)})** have source-to-sink reachability below "
        f"1.000. {broken['meaning']}.\n"
    )
    w(
        f"Reachability against R: {rho_cell(chain['spearman_reachability_vs_r'])}. "
        f"Reachability by verified data sharing: rank-biserial "
        f"{signed(chain['reachability_by_sharing'].get('rank_biserial_r'), 3)} "
        f"{ci(chain['reachability_by_sharing'], 3, 'signed')}, "
        f"{p(chain['reachability_by_sharing'].get('p_value'))}. R split on chain integrity: "
        f"rank-biserial {signed(chain['r_by_chain_integrity'].get('rank_biserial_r'), 3)} "
        f"{ci(chain['r_by_chain_integrity'], 3, 'signed')}, "
        f"{p(chain['r_by_chain_integrity'].get('p_value'))}.\n"
    )

    sink = a["A5.5"]
    w("### Sink quality, pre-registered for Stage 3 (A5.5)\n")
    w("| statement clarity | nodes | fraction |")
    w("|---|---|---|")
    for level, count in sink["statement_clarity"]["counts"].items():
        w(
            f"| {level} | {count} "
            f"| {fmt(sink['statement_clarity']['fractions'][level], percent=True)} |"
        )
    w("\n| statement validity | nodes | fraction |")
    w("|---|---|---|")
    for label, count in sink["statement_validity"]["counts"].items():
        w(
            f"| `{label}` | {count} "
            f"| {fmt(sink['statement_validity']['fractions'][label], percent=True)} |"
        )
    prereg = sink["stage3_preregistered_comparison"]
    w(
        f"\n**Pre-registered comparison.** {prereg['papers_ara_marks_unclear']} papers meet "
        f"`{prereg['threshold']}`. {sentence(prereg['prediction'])}. The paper ids are recorded in the "
        f"analysis JSON under `A5.5.stage3_preregistered_comparison.paper_ids`.\n"
    )

    complexity = a["A5.6"]
    w("### Workflow complexity against R (A5.6)\n")
    w("| node count | mean | Spearman with R |")
    w("|---|---|---|")
    for count, block in complexity["node_counts"].items():
        w(
            f"| `{count}` | {fmt(block['mean'], 2)} "
            f"| {rho_cell(complexity['spearman_with_r'][count])} |"
        )
    partial_nodes = complexity["partial_nodes_vs_r_given_length"]
    w(
        f"\nNode count against paper length: "
        f"{rho_cell(complexity['spearman_nodes_vs_length'])}. Partial correlation of node "
        f"count with R once length is removed: {signed(partial_nodes.get('partial_rho'), 3)} "
        f"{ci(partial_nodes, 3, 'signed')} on n={partial_nodes['n']}. "
        f"{sentence(complexity['interpretation_rule'])}.\n"
    )

    cross = a["A5.7"]
    w("### ARA against Stage 1 on data availability (A5.7)\n")
    w(f"{sentence(cross['instruments'])}.\n")
    w("| comparison | n | observed agreement | Cohen's kappa |")
    w("|---|---|---|---|")
    for label, key in (
        ("ARA source availability against Stage 1 `open_data`", "availability_vs_open_data"),
        ("ARA licence against Stage 1 `license`", "license_vs_license"),
        ("ARA source availability against verified retrieval", "availability_vs_verified_retrieval"),
    ):
        block = cross[key]
        w(
            f"| {label} | {block['n']} "
            f"| {fmt(block['observed_agreement'], percent=True)} "
            f"| {fmt(block['kappa'], 3)} |"
        )
    w(
        f"\nBoth instruments call the data open for {cross['both_say_open']} papers; ARA alone "
        f"for {cross['ara_says_open_only']}; Stage 1 alone for {cross['stage1_says_open_only']}. "
        f"ARA reports an open source but nothing was retrieved for "
        f"{cross['ara_open_but_nothing_retrieved']} papers. {sentence(cross['reading'])}.\n"
    )

    w("## 8. Cross-model sensitivity (A6.1)\n")
    luna = a["A6.1"]
    if luna.get("status") == "probe absent":
        w("The cross-model probe is not present in this database.\n")
    else:
        w(f"Status: {luna['status']}.\n")
        w("| paper | terra R | luna R | difference |")
        w("|---|---|---|---|")
        for pair in luna["papers"]:
            w(
                f"| {pair['paper_id']} | {fmt(pair['terra_r'], 3)} | {fmt(pair['luna_r'], 3)} "
                f"| {signed(pair['difference'], 3)} |"
            )
        w(
            f"\n**n={luna['n']}.** Mean shift {signed(luna['mean_shift'], 3)}; luna scores every "
            f"paper higher: {fmt(luna['luna_higher_on_all_papers'])}. Ranking agreement: "
            f"{rho_cell(luna['spearman_ranking'])}. {luna['decision_reference']}.\n"
        )

    w("## 9. Reserved for Stage 4 (A7.1)\n")
    stage4 = a["A7.1"]
    w(
        f"Status: **{stage4['status']}**. {stage4['reason']}. "
        f"{stage4['executable_candidates']} papers currently have both a verified retrievable "
        f"dataset and a fetched code repository. Blocked by {stage4['blocked_by']}.\n"
    )

    w("## 10. Figures\n")
    w(f"Written to `{args.figures}` as `.png` and `.svg` at 300 dpi.\n")
    w("| id | content |")
    w("|---|---|")
    for stem, description in (
        ("F1", "R by year, six violins with quartiles and per-year n"),
        ("F2", "R by claim type, ordered by median"),
        ("F3", "R_c against R_s with marginal densities and the structural ceiling"),
        ("F3b", "Stage score distributions: sources, methods, experiments, outputs"),
        ("F4", "Trend contrast: mean R with CI band against verified data sharing"),
        ("F5", "R by verified artifact availability"),
        ("F6", "tau_R sensitivity with the run-to-run noise band"),
        ("F7", "Bland–Altman drift check"),
        ("F8", "Within-paper SD of R against ARA's reported band"),
        ("F9", "Node deficit by node class with CIs"),
        ("F10", "Parameter gap, named against required, by year"),
    ):
        w(f"| `{stem}` | {description} |")
    w("\nRegenerate any of them from the")
    w(f"JSON alone with `uv run lakdb rstats figures --from {args.input}`, which does not read")
    w("the database.\n")

    pathlib.Path(args.output).write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {args.output} ({len(out)} lines)")


