# `_SIGNATURES` contains only public canonical Click commands.
_CANONICAL_SIGNATURES = _SIGNATURES


def nushell_module() -> str:
    """Return deterministic native completion definitions for the Click CLI."""
    blocks = [_HELPERS]
    for prefix in ("lakdb", "uv run lakdb"):
        for command, arguments in _CANONICAL_SIGNATURES:
            name = f"{prefix} {command}".strip()
            lines = [f'export extern "{name}" [']
            lines.extend(f"    {argument}" for argument in arguments)
            lines.append("]\n")
            blocks.append("\n".join(lines))
    body = "".join(blocks)
    indented = "\n".join(f"    {line}" if line else "" for line in body.splitlines())
    return (
        GENERATED_HEADER
        + 'module "lakdb native completions" {\n'
        + indented
        + '\n}\n\nexport use "lakdb native completions" *\n'
    )


def _short_title(value: str | None) -> str:
    title = " ".join((value or "[untitled]").split())
    return title if len(title) <= 20 else title[:20] + "…"


def completion_candidates(
    database: Path,
    candidate_type: str,
    *,
    experiment: str | None = None,
    year: int | None = None,
    status: str | None = None,
    paper_kind: str | None = None,
) -> list[dict[str, str]]:
    """Read completion records without creating or modifying a database."""
    path = database.expanduser()
    if not path.is_file():
        return []
    try:
        connection = sqlite3.connect(
            f"file:{path.resolve().as_posix()}?mode=ro", uri=True
        )
        connection.row_factory = sqlite3.Row
        connection.execute("PRAGMA query_only=ON")
        if candidate_type == "experiments":
            clauses: list[str] = []
            params: list[Any] = []
            if experiment:
                clauses.append("e.name=?")
                params.append(experiment)
            if status:
                clauses.append("e.status=?")
                params.append(status)
            rows = connection.execute(
                "SELECT e.name,e.status,e.model,COUNT(DISTINCT r.paper_id) papers,"
                "COUNT(r.id) runs,SUM(CASE WHEN r.status='succeeded' THEN 1 ELSE 0 END) succeeded "
                "FROM study_experiments e LEFT JOIN applicability_runs r ON r.experiment_id=e.id"
                + (" WHERE " + " AND ".join(clauses) if clauses else "")
                + " GROUP BY e.id ORDER BY e.name",
                params,
            ).fetchall()
            return [
                {
                    "value": str(row["name"]),
                    "description": f"{row['status']} · {row['model']} · {row['papers']} papers · {row['succeeded'] or 0}/{row['runs']} successful runs",
                }
                for row in rows
            ]
        if candidate_type == "ara-experiments":
            clauses = []
            params = []
            if experiment:
                clauses.append("e.name=?")
                params.append(experiment)
            if status:
                clauses.append("e.status=?")
                params.append(status)
            rows = connection.execute(
                "SELECT e.name,e.status,e.model,COUNT(DISTINCT r.paper_id) papers,"
                "COUNT(r.id) runs,SUM(CASE WHEN r.status='succeeded' THEN 1 ELSE 0 END) succeeded "
                "FROM ara_experiments e LEFT JOIN ara_runs r ON r.experiment_id=e.id"
                + (" WHERE " + " AND ".join(clauses) if clauses else "")
                + " GROUP BY e.id ORDER BY e.name",
                params,
            ).fetchall()
            return [
                {
                    "value": str(row["name"]),
                    "description": f"{row['status']} · {row['model']} · {row['papers']} papers · {row['succeeded'] or 0}/{row['runs']} successful runs",
                }
                for row in rows
            ]
        if candidate_type == "artifact-experiments":
            clauses = []
            params = []
            if experiment:
                clauses.append("e.name=?")
                params.append(experiment)
            if status:
                clauses.append("e.status=?")
                params.append(status)
            try:
                rows = connection.execute(
                    "SELECT e.name,e.status,e.stage,e.model,COUNT(DISTINCT r.paper_id) papers,"
                    "COUNT(r.id) runs,SUM(CASE WHEN r.status='succeeded' THEN 1 ELSE 0 END) succeeded "
                    "FROM artifact_experiments e LEFT JOIN artifact_runs r ON r.experiment_id=e.id"
                    + (" WHERE " + " AND ".join(clauses) if clauses else "")
                    + " GROUP BY e.id ORDER BY e.name",
                    params,
                ).fetchall()
            except sqlite3.Error:
                return []
            return [
                {
                    "value": str(row["name"]),
                    "description": f"{row['status']} · {row['stage']} · {row['model']} · {row['papers']} papers · {row['succeeded'] or 0}/{row['runs']} successful runs",
                }
                for row in rows
            ]
        if candidate_type == "artifact-batches":
            clauses = []
            params = []
            if experiment:
                clauses.append("e.name=?")
                params.append(experiment)
            if status:
                clauses.append("b.status=?")
                params.append(status)
            try:
                rows = connection.execute(
                    "SELECT b.id,b.status,b.request_count,e.name FROM artifact_batch_jobs b "
                    "JOIN artifact_experiments e ON e.id=b.experiment_id"
                    + (" WHERE " + " AND ".join(clauses) if clauses else "")
                    + " ORDER BY b.id DESC",
                    params,
                ).fetchall()
            except sqlite3.Error:
                return []
            return [
                {
                    "value": str(row["id"]),
                    "description": f"{row['status']} · {row['request_count']} requests · {row['name']}",
                }
                for row in rows
            ]
        if candidate_type == "batches":
            clauses = []
            params = []
            if experiment:
                clauses.append("e.name=?")
                params.append(experiment)
            if status:
                clauses.append("b.status=?")
                params.append(status)
            rows = connection.execute(
                "SELECT b.id,b.status,b.request_count,e.name FROM openai_batch_jobs b "
                "JOIN study_experiments e ON e.id=b.experiment_id"
                + (" WHERE " + " AND ".join(clauses) if clauses else "")
                + " ORDER BY b.id DESC",
                params,
            ).fetchall()
            return [
                {
                    "value": str(row["id"]),
                    "description": f"{row['status']} · {row['request_count']} requests · {row['name']}",
                }
                for row in rows
            ]
        if candidate_type == "papers":
            clauses = ["fa.paper_id IS NOT NULL"]
            params = []
            joins = ""
            label_column = "NULL"
            if experiment or status:
                joins = (
                    " LEFT JOIN applicability_decisions d ON d.paper_id=p.id"
                    " LEFT JOIN study_experiments e ON e.id=d.experiment_id"
                )
                label_column = "MAX(d.final_label)"
                if experiment:
                    clauses.append("e.name=?")
                    params.append(experiment)
                if status:
                    clauses.append("d.final_label=?")
                    params.append(status)
            if year is not None:
                clauses.append("p.collection_year=?")
                params.append(year)
            if paper_kind:
                clauses.append("fa.paper_kind=?")
                params.append(paper_kind)
            rows = connection.execute(
                f"SELECT p.id,p.collection_year,p.title,MIN(fa.paper_kind) paper_kind,{label_column} final_label "
                "FROM papers p JOIN file_assets fa ON fa.paper_id=p.id"
                + joins
                + " WHERE "
                + " AND ".join(clauses)
                + " GROUP BY p.id ORDER BY p.collection_year,p.title,p.id",
                params,
            ).fetchall()
            return [
                {
                    "value": str(row["id"]),
                    "description": " · ".join(
                        part
                        for part in (
                            str(row["collection_year"] or "—"),
                            _short_title(row["title"]),
                            str(row["paper_kind"] or "—"),
                            str(row["final_label"] or ""),
                        )
                        if part
                    ),
                }
                for row in rows
            ]
        return []
    except sqlite3.Error:
        return []
    finally:
        if "connection" in locals():
            connection.close()


def candidates_json(records: list[dict[str, str]]) -> str:
    # Shell completion protocols must be UTF-8-safe even when a Windows console
    # inherits a legacy code page; ASCII escapes keep every JSON byte portable.
    return json.dumps(
        records, ensure_ascii=True, sort_keys=True, separators=(",", ":")
    )
